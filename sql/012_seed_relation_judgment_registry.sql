ЛЕЙБЛИ (рівно один із п'яти, обов'язковий пріоритет застосування зверху вниз —
перший, що підходить, і є відповіддю; НЕ обирай "сильніший" лейбл, якщо умови
менш пріоритетного вже виконані, а більш пріоритетного — ні):

1. contradiction — НАЙВИЩИЙ пріоритет. Застосовуй ТІЛЬКИ якщо ОБИДВІ умови
   виконані одночасно:
   a) claim A і claim B стосуються ОДНОГО й того самого референта (та сама
      подія/об'єкт/показник, а не просто схожа тема);
   b) вони НЕ можуть бути одночасно істинними САМЕ ПРИ ОДНАКОВОМУ
      scope/часі/метриці — тобто ти можеш явно підтвердити з тексту, що
      referent, часове вікно і те, що саме вимірюється чи стверджується,
      збігаються, і при цьому значення/факти взаємовиключні.
   Якщо збіг scope/часу/метрики НЕ підтверджений явно з тексту (наприклад,
   різні одиниці виміру, різний масштаб події, невідомо — та сама хвиля
   мобілізації чи інша, той самий підрозділ чи інший) — це НЕ contradiction,
   навіть якщо цифри чи факти виглядають несумісними.
   Приклад: claim A "дезертирували 80 осіб", claim B "втекли кілька сотень" —
   САМІ ПО СОБІ це НЕ contradiction, доки не підтверджено, що йдеться про той
   самий підрозділ/період/подію; якщо scope не підтверджений — став related
   або unrelated (дивись нижче), а НЕ contradiction.

2. same_fact — якщо (1) не підходить. Обидва claims стверджують, по суті,
   ОДИН і той самий факт/подію з тим самим змістом (можливо, іншою мовою чи
   формулюванням, можливо з різним рівнем деталізації, але без суперечності і
   без істотно різного обсягу інформації).

3. same_event — якщо (1) і (2) не підходять. Обидва claims стосуються ОДНІЄЇ
   й тієї самої конкретної події/інциденту, але повідомляють про РІЗНІ її
   аспекти чи деталі (а не той самий факт), і не суперечать один одному.

4. related — якщо (1)–(3) не підходять. Claims пов'язані змістовно (той самий
   ширший контекст, напрямок, тема, учасники), але НЕ описують один і той
   самий конкретний референт/подію.

5. unrelated — якщо жодна з умов (1)–(4) не виконується. Це включає випадок,
   коли claims просто містять однакові ЗАГАЛЬНІ/шаблонні фрази (наприклад,
   "на місці удару працюють екстрені служби", "ворог продовжує обстріли") без
   жодного спільного конкретного референта — сама по собі текстова схожість
   шаблонної фрази НЕ є доказом спільного факту чи події.

