КРОК 1 — ПЕРЕВІРКА СПІЛЬНОГО РЕФЕРЕНТА (shared_referent_status)

Визнач, чи claim A і claim B стосуються ОДНОГО й того самого конкретного
референта (та сама подія/об'єкт/особа/показник), спираючись на ВСІ надані
дані (claim_text, evidence_span, title, context_snippet) обох claims, а не
лише на claim_text окремо.

Встанови одне з трьох значень:
- "confirmed" — спільний референт ПІДТВЕРДЖЕНИЙ конкретною ідентифікуючою
  ознакою, яка присутня в наданих даних ОБОХ claims: та сама локація, дата чи
  часовий проміжок, названий об'єкт, учасник чи сторона, унікальна деталь у
  поєднанні з іншою специфікою тощо.
- "not_confirmed" — дані обох claims присутні й достатні, але спільного
  референта НЕ підтверджено (немає жодної ідентифікуючої ознаки, що
  збігається, або є ознаки, що вказують на РІЗНІ референти).
- "insufficient" — наданих даних (claim_text/evidence_span/title/
  context_snippet) НЕДОСТАТНЬО, щоб взагалі оцінити, чи це той самий
  референт.

НЕДОСТАТНЬО для "confirmed" (кожен із цих факторів окремо чи разом, без
конкретної ідентифікуючої деталі, НЕ є підтвердженням):
- самé лише числове співпадіння (наприклад, однакова кількість постраждалих);
- загальна або шаблонна фраза про дію чи результат (наприклад, "екстрені
  служби працюють на місці", "постраждалих немає", "затримали людину");
- те, що один claim є перекладом чи перефразуванням іншого;
- відсутність ознак, що вказують на РІЗНІ референти — це НЕ доказ спільного
  референта. Тягар доведення лежить на підтвердженні схожості, а не на
  відсутності відмінностей.

shared_referent_evidence — обов'язкове текстове поле, завжди непорожнє.
Якщо status="confirmed": процитуй ТОЧНО (у лапках «...») конкретний фрагмент
