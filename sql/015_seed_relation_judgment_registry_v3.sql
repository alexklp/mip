чого саме бракує — цитати тут не обов'язкові.

КРОК 2 — ЛЕЙБЛ ЗВ'ЯЗКУ (relation_label)

ЖОРСТКЕ ПРАВИЛО: лейбли contradiction, same_fact, same_event ДОЗВОЛЕНІ
ТІЛЬКИ якщо shared_referent_status="confirmed". Якщо status="not_confirmed"
або "insufficient" — застосовуй ЛИШЕ related або unrelated, незалежно від
того, наскільки текстуально схожими виглядають claims.

Якщо shared_referent_status="confirmed", обирай один із п'яти лейблів за
пріоритетом зверху вниз (перший, що підходить, — відповідь):

1. contradiction — НАЙВИЩИЙ пріоритет. Референт уже підтверджено Кроком 1.
   Додатково потрібно підтвердити, що часове вікно і те, що саме
   вимірюється чи стверджується (scope/метрика), ТЕЖ збігаються, і при цьому
   значення чи факти взаємовиключні. Якщо збіг scope/часу/метрики НЕ
   підтверджений явно з наданих даних — це НЕ contradiction, навіть якщо
   цифри чи факти виглядають несумісними.
   Приклад: claim A "дезертирували 80 осіб", claim B "втекли кілька сотень"
   — навіть якщо shared_referent_status="confirmed" (той самий підрозділ чи
   подія), це САМЕ ПО СОБІ ще НЕ contradiction, доки не підтверджено, що
   йдеться про той самий період і те саме охоплення; якщо scope не
   підтверджений — обирай same_event або related, а НЕ contradiction.

2. same_fact — якщо (1) не підходить. Обидва claims стверджують ОДИН і той
   самий конкретний факт про підтверджений спільний референт і не
   суперечать один одному.

3. same_event — якщо (1) і (2) не підходять. Обидва claims стосуються
   ОДНІЄЇ й тієї самої підтвердженої події/інциденту, але повідомляють про
   РІЗНІ її аспекти чи деталі (а не той самий факт), і не суперечать один
   одному.

4. related — якщо (1)–(3) не підходять, АБО якщо shared_referent_status
   "not_confirmed"/"insufficient", але claims пов'язані змістовно (той самий
   ширший контекст, напрямок, тема, учасники) без підтвердженого спільного
   референта.

5. unrelated — якщо жодна з умов (1)–(4) не виконується. Це включає випадок,
   коли claims просто містять однакові ЗАГАЛЬНІ/шаблонні фрази без жодного
   спільного конкретного референта — сама по собі текстова схожість
   шаблонної фрази НЕ є доказом зв'язку.

