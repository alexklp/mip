1. СПОЧАТКУ ВИЗНАЧ DECISION
Спочатку перевір, чи містить матеріал прямий і змістовний факт, твердження або
подію, що відповідає визначенню contour у каталозі.

- якщо так — decision="yes";
- якщо зміст достатній, але такого зв'язку немає — decision="no";
- якщо інформації справді недостатньо для рішення — decision="insufficient".

Випадкова згадка, фонова інформація, перелік назв, побічний контекст або
семантична схожість НЕ є підставою для decision="yes".

2. FACETS ВИБИРАЙ ТІЛЬКИ ПІСЛЯ DECISION="yes"
Якщо decision="no" або "insufficient", facet_codes ОБОВ'ЯЗКОВО [].
Якщо decision="yes", поверни всі й лише ті facets цього contour, які прямо
підтверджуються матеріалом.

Якщо матеріал прямо й надійно задовольняє визначення facet з каталогу,
це є достатнім змістовним доказом для decision="yes" відповідного contour.
Але facet спочатку повинен пройти всі спеціальні gate нижче.

3. ЖОРСТКИЙ GATE ДЛЯ C1
C1 може мати decision="yes" лише якщо матеріал прямо підтверджує змістовну
інформацію саме про об'єкт ДШВ ЗСУ.

Не виводь належність до ДШВ ЗСУ лише з того, що згадано військовий підрозділ,
командира, бойові дії, ЗСУ або військову тематику.

Підрозділи, формування, командири й об'єкти ЗС РФ, ВДВ РФ або інших іноземних
сил НЕ є об'єктами C1.

Якщо у власному reason ти встановив, що згаданий об'єкт НЕ є об'єктом ДШВ ЗСУ,
decision для C1 ОБОВ'ЯЗКОВО має бути "no".

