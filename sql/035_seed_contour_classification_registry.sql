Заява посадовця РФ ПРО НАТО — не nato_statements.
Заява представника або посадовця НАТО — також не nato_statements, якщо ця
особа не є одночасно лідером країни НАТО.

Якщо єдиною можливою підставою для C2 є nato_statements, але цей gate не
виконано, C2 ОБОВ'ЯЗКОВО має decision="no".

6. GATE ДЛЯ НАПРЯМКУ УРАЖЕННЯ
