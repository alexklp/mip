def key(text: str) -> str:
    return " ".join(text.casefold().split())


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    # Remove case/whitespace duplicates inside the pack itself.
    pack = {}
    for object_id, aliases in PACK.items():
        seen = set()
        pack[object_id] = []
        for alias in aliases:
            alias = alias.strip()
            normalized = key(alias)
            if not alias or normalized in seen:
                continue
            seen.add(normalized)
            pack[object_id].append(alias)

    with psycopg.connect(DB_DSN) as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT object_id, canonical_name
                FROM contour_reference_objects
                WHERE monitoring_contour_id = 1
                  AND active
                """
            )
            objects = {
                object_id: canonical_name
                for object_id, canonical_name in cur.fetchall()
            }

            cur.execute(
                """
                SELECT object_id, reference_text
                FROM contour_reference_entries
                WHERE monitoring_contour_id = 1
                  AND object_id IS NOT NULL
                  AND entry_type = 'alias'
                  AND active
                """
            )
            existing = {
                (object_id, key(reference_text))
                for object_id, reference_text in cur.fetchall()
            }

        pending = []

        for object_id, aliases in pack.items():
            if object_id not in objects:
                raise RuntimeError(
                    f"Unknown or inactive C1 object_id={object_id}"
                )

            for alias in aliases:
                if (object_id, key(alias)) in existing:
                    continue
                pending.append((object_id, alias))

        print(f"pack_unique={sum(len(v) for v in pack.values())}")
        print(f"already_present={sum(len(v) for v in pack.values()) - len(pending)}")
        print(f"pending={len(pending)}")
        print(f"mode={'WRITE' if args.write else 'DRY-RUN'}")

        if not args.write:
            return 0

        inserted = 0

        with conn.cursor() as cur:
            for object_id, alias in pending:
                cur.execute(
                    """
                    INSERT INTO contour_reference_entries (
                        monitoring_contour_id,
                        object_id,
                        entry_type,
                        match_mode,
                        facet_code,
                        reference_text,
                        active,
                        reference_version,
                        source_note,
                        verification_status,
                        verified_on
                    )
                    VALUES (
                        1,
                        %s,
                        'alias',
                        'exact',
                        NULL,
                        %s,
                        true,
                        1,
                        %s,
                        'candidate',
                        NULL
                    )
                    ON CONFLICT DO NOTHING
                    """,
                    (object_id, alias, SOURCE_NOTE),
                )
                inserted += cur.rowcount

        conn.commit()

        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT count(*)
                FROM contour_reference_entries
                WHERE monitoring_contour_id = 1
                  AND source_note = %s
                  AND verification_status = 'candidate'
                  AND active
                """,
                (SOURCE_NOTE,),
            )
            pack_rows = cur.fetchone()[0]

        print(f"inserted={inserted}")
        print(f"pack_rows_in_db={pack_rows}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
